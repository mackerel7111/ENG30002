def _score_model_file(pkl_path, X_hold, y_hold):
    """
    Load a saved model file and return its F1 score on the holdout set.
    Used to compare models against each other.
    """
    with open(pkl_path, "rb") as f:
        m = pickle.load(f)
    y_pred = m.predict(X_hold)
    return f1_score(y_hold, y_pred, zero_division=0)


def _save_model_metadata(model_path, metrics, train_count, flood_count):
    """Save JSON metadata alongside a model file.
    
    Metadata includes: timestamp, F1, accuracy, AUC, train/flood counts.
    Useful for reproducibility and audit trails.
    """
    metadata_path = Path(model_path).with_suffix('.json')
    metadata = {
        "model_file": Path(model_path).name,
        "timestamp": datetime.now().isoformat(),
        "metrics": {
            "f1": float(metrics.get("f1", 0)),
            "accuracy": float(metrics.get("acc", 0)),
            "auc": float(metrics.get("auc", 0)),
        },
        "training_data": {
            "total_rows": int(train_count),
            "flood_events": int(flood_count),
            "flood_ratio": float(flood_count / train_count) if train_count > 0 else 0,
        }
    }
    with open(metadata_path, "w") as f:
        json.dump(metadata, f, indent=2)
    print(f"  [metadata] Saved → {metadata_path}")


def get_archive():
    """
    Return a sorted list of all saved model file paths in models/ folder.
    Excludes best_model.pkl itself.
    """
    files = sorted([
        f for f in os.listdir(ARCHIVE_DIR)
        if f.endswith(".pkl")
    ])
    return [str(ARCHIVE_DIR / f) for f in files]

def _update_best_model(X_hold, y_hold):
    """
    Score all archived models, find the best one, and copy it to
    best_model.pkl. The dashboard always loads best_model.pkl —
    this ensures it always gets the best performing version.
    """
    archive = get_archive()
    if not archive:
        return None

    scores    = {p: _score_model_file(p, X_hold, y_hold) for p in archive}
    best_path = max(scores, key=scores.get)
    best_f1   = scores[best_path]

    shutil.copy(best_path, BEST_MODEL_PATH)
    print(f"  [best] {BEST_MODEL_PATH.name} updated → "
          f"{os.path.basename(best_path)} (F1={best_f1:.4f})")
    return best_path

def _list_region_archive(region: str):
    """Return list of archive files for a given region, sorted."""
    files = sorted([
        f for f in os.listdir(ARCHIVE_DIR)
        if f.endswith(".pkl") and f.startswith(f"model_{region}_")
    ])
    return [str(ARCHIVE_DIR / f) for f in files]


def _save_region_model_legacy(model, region: str, version_tag: str, X_hold, y_hold):
    """
    Atomically save a model for a specific region.
    - archive: models/archive/model_<region>_<version>.pkl
    - current: models/current/<region>.pkl (atomic replace)
    - perform archive rotation per-region using F1 on holdout
    - save metadata JSON for reproducibility
    """
    # Archive save (atomic)
    archive_name = f"model_{region}_{version_tag}.pkl"
    archive_path = ARCHIVE_DIR / archive_name
    tmp_archive  = ARCHIVE_DIR / (archive_name + ".tmp")
    with open(tmp_archive, "wb") as f:
        pickle.dump(model, f)
    os.replace(tmp_archive, archive_path)
    print(f"  [archive:{region}] Saved → {archive_path}")

    # Score and save metadata
    y_pred = model.predict(X_hold)
    metrics = evaluate(model, X_hold, y_hold, label="")
    _save_model_metadata(str(archive_path), metrics, len(X_hold), int(y_hold.sum()))

    # Deploy current model atomically
    current_name = f"{region}.pkl"
    current_path = CURRENT_DIR / current_name
    tmp_current  = CURRENT_DIR / (current_name + ".tmp")
    with open(tmp_current, "wb") as f:
        pickle.dump(model, f)
    os.replace(tmp_current, current_path)
    print(f"  [current:{region}] Deployed → {current_path}")

    # Archive rotation per-region
    files = _list_region_archive(region)
    if len(files) > MAX_MODELS:
        print(f"  [archive:{region}] Cap of {MAX_MODELS} exceeded. Scoring models...")
        scores = {p: _score_model_file(p, X_hold, y_hold) for p in files}
        for p, s in scores.items():
            print(f"    {os.path.basename(p)}: F1={s:.4f}")
        worst = min(scores, key=scores.get)
        os.remove(worst)
        # Also remove metadata if it exists
        metadata_path = Path(worst).with_suffix('.json')
        if metadata_path.exists():
            os.remove(metadata_path)
        print(f"  [archive:{region}] Removed worst → {os.path.basename(worst)} "
              f"(F1={scores[worst]:.4f})")

    return str(archive_path)

