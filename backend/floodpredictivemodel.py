# Region csv utilities
# rolling window logic
# return true when threshold is hit, then triggers retraining feature

def _append_rolling(csv_path, new_rows: pd.DataFrame):
    """
    Append new_rows to the region CSV.
    When the file grows beyond ROLLING_KEEP_SIZE + ROLLING_SIZE,
    drop the oldest ROLLING_SIZE rows. Returns
    (updated_df, retrain_triggered).
    """
    new_rows = _ensure_training_metadata_columns(new_rows)
    if os.path.exists(csv_path):
        existing = _ensure_training_metadata_columns(pd.read_csv(csv_path))
        combined = pd.concat([existing, new_rows], ignore_index=True)
    else:
        combined = new_rows.copy()

    retrain_triggered = False
    threshold = ROLLING_KEEP_SIZE + ROLLING_SIZE
    while len(combined) >= threshold:
        combined          = combined.iloc[ROLLING_SIZE:].reset_index(drop=True)
        retrain_triggered = True
        print(f"  [rolling] Dropped oldest {ROLLING_SIZE} rows from "
              f"{os.path.basename(csv_path)}. "
              f"Remaining: {len(combined)} rows "
              f"(target: {ROLLING_KEEP_SIZE}).")

    combined.to_csv(csv_path, index=False)
    return combined, retrain_triggered


def _ensure_training_metadata_columns(df: pd.DataFrame):
    """Keep live/raw rows explicit about synthetic status and flood type labels."""
    df = df.copy()
    if SYNTHETIC_COL not in df.columns:
        df[SYNTHETIC_COL] = False
    else:
        df[SYNTHETIC_COL] = df[SYNTHETIC_COL].fillna(False)

    if FLOOD_TYPE_COL not in df.columns:
        df[FLOOD_TYPE_COL] = UNLABELLED_FLOOD_TYPE
    else:
        df[FLOOD_TYPE_COL] = df[FLOOD_TYPE_COL].replace("", np.nan)
        df[FLOOD_TYPE_COL] = df[FLOOD_TYPE_COL].fillna(UNLABELLED_FLOOD_TYPE)

    for column, default in TRAINING_METADATA_DEFAULTS.items():
        if column not in df.columns:
            df[column] = default
        else:
            df[column] = df[column].fillna(default)
    return df


